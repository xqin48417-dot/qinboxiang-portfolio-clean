const normalizeAssetTitle = (title, groupKey, index) => {
  const cleaned = String(title || "")
    .replace(/\.(png|jpe?g|webp|gif)$/i, "")
    .replace(/^本地/, "")
    .replace(/^[._\-\s]+/, "")
    .replace(/\s+/g, " ")
    .trim();

  const fallback = `${assetGroupLabelMap[groupKey] || "画面"} ${String(index + 1).padStart(2, "0")}`;
  if (!cleaned) return fallback;

  const looksTechnical =
    /^GPT Image/i.test(cleaned) ||
    /^[0-9a-f]{8}-[0-9a-f-]{27,}$/i.test(cleaned) ||
    /^\d{12,}/.test(cleaned) ||
    /^\d+$/.test(cleaned);

  return looksTechnical ? fallback : cleaned;
};

